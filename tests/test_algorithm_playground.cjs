const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const esbuild=require('../web/node_modules/esbuild')
const root=path.resolve(__dirname,'..')
const src=fs.readFileSync(path.join(root,'web/src/algorithmSteps.ts'),'utf8')
const output=esbuild.transformSync(src,{loader:'ts',format:'cjs',target:'es2022'}).code
const moduleRef={exports:{}}
new Function('module','exports',output)(moduleRef,moduleRef.exports)
const api=moduleRef.exports
const methods=['K-Means','Decision Tree','Apriori','FP-Growth','Eclat']
for(const name of methods){
 const frames=api.makeFrames(name)
 assert.ok(frames.length>=4,name+': missing interactive steps')
 assert.ok(frames.every(f=>f.title&&f.formula&&f.detail&&f.note),name+': incomplete stage')
}
const km=api.kMeansFrames()
assert.deepEqual(km[0].centroids.map(c=>c.x),[1,2.2])
const final=km.at(-1)
assert.match(final.title,/converged/)
assert.deepEqual(final.assignments,[0,0,0,1,1,1])
assert.ok(final.centroids.some(c=>Math.abs(c.x-1.6)<1e-9))
assert.ok(final.centroids.some(c=>Math.abs(c.x-(6+7.3+6.4)/3)<1e-9))
const apr=api.aprioriFrames()
const pairs=apr.find(f=>f.title.includes('2-item'))
assert.equal(pairs.items.length,3)
assert.ok(pairs.items.every(s=>s.count===3&&s.pass))
const triple=apr.find(f=>f.title.includes('Prune the infrequent triple'))
assert.ok(triple.items.some(s=>s.name==='A+B+C'&&s.count===2&&!s.pass))
const fp=api.fpFrames()
const inserted=fp.filter(f=>f.tree&&f.title.includes('Insert'))
assert.equal(inserted.length,5)
assert.equal(inserted.at(-1).tree.find(t=>t.path==='A/B/C').count,2)
const ec=api.eclatFrames()
assert.match(ec.find(f=>f.title.includes('A+B+C')).formula,/TID\(A\) ∩ TID\(B\) ∩ TID\(C\)/)
assert.match(ec.find(f=>f.title.includes('A+B+C')).formula,/{T1,T5}/)
const lab=fs.readFileSync(path.join(root,'web/src/SyllabusLab.tsx'),'utf8')
for(const topic of ['classification','clustering','patterns'])assert.match(lab,new RegExp('AlgorithmPlayground topic="'+topic+'"'))
assert.match(lab,/cache:'no-store'/)
assert.match(lab,/Retry loading data|ResourceError/)
const hub=fs.readFileSync(path.join(root,'web/src/SyllabusHub.tsx'),'utf8')
assert.match(hub,/ResourceError/)
const app=fs.readFileSync(path.join(root,'web/src/App.tsx'),'utf8')
assert.match(app,/WarehouseLoading progress=/)
assert.match(app,/ResourceError/)
const db=fs.readFileSync(path.join(root,'web/src/db.ts'),'utf8')
assert.match(db,/completed\+\+/)
assert.match(db,/onProgress/)
console.log('PASS: five computed teaching algorithms, real data progress, recoverable fetch and original research integration')
