const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.join(__dirname,'..')
const app=fs.readFileSync(path.join(root,'web/src/App.tsx'),'utf8')
const types=fs.readFileSync(path.join(root,'web/src/types.ts'),'utf8')
const syllabus=fs.readFileSync(path.join(root,'web/src/SyllabusLab.tsx'),'utf8')
const hub=fs.readFileSync(path.join(root,'web/src/SyllabusHub.tsx'),'utf8')
const science=fs.readFileSync(path.join(root,'scripts/build_mining_lab.py'),'utf8')
const nav=app.match(/const NAV:[\s\S]*?\n\]/)?.[0]||''
const declared=(nav.match(/\{\s*label:\s*'/g)||[]).length
assert.equal(declared,19,'preserve original 12 routes, six syllabus modules and syllabus navigation hub')
const modules=['Warehouse & ETL','Data Lakes','EDA & Preprocessing','Classification Lab','Clustering Lab','Pattern Mining']
for(const name of modules){
 assert.ok(nav.includes("label: '"+name+"'"),'missing navigation '+name)
 assert.ok(types.includes("'"+name+"'"),'missing route type '+name)
 assert.ok(app.includes('<SyllabusLab module="'+name+'"/>'),'missing full UI render '+name)
 assert.ok(syllabus.includes("'"+name+"'"),'missing module implementation '+name)
}
assert.match(syllabus,/data\/mining_lab\.json/,'read real generated export')
assert.match(syllabus,/Export empirical CSV/,'source exports')
assert.match(syllabus,/syllabus-dendrogram/,'actual dendrogram renderer')
assert.match(syllabus,/Math\.abs\(item.value\)/,'Pearson matrix plotting')
assert.match(science,/orders\.is_late/,'missingness and classification labels verified in offline pipeline')
assert.match(science,/DecisionTreeClassifier/)
assert.match(science,/GaussianNB/)
assert.match(science,/LinearRegression/)
assert.match(science,/AgglomerativeClustering/)
assert.match(science,/BisectingKMeans/)
assert.match(science,/KMeans/)
assert.match(science,/linkage\(subset/)
assert.match(science,/apriori,\s*fpgrowth,\s*association_rules/)
assert.match(science,/def eclat\(/)
assert.match(science,/closed_itemsets_total/,'full mined closed frequent itemset output')
assert.match(syllabus,/Closed frequent itemsets/,'closed-itemset evidence interface')
assert.match(syllabus,/same observed support/,'explicit closure criterion')
assert.match(science,/random_state=SEED/)
assert.match(science,/valid_split/)
assert.match(science,/fact_order_items/)
assert.match(science,/fact_orders/)
assert.ok(nav.includes("label: 'Syllabus Hub'"))
assert.ok(app.includes('<SyllabusHub onNavigate={changePage}/>'))
assert.ok(hub.includes('syllabus-hub-hours')&&hub.includes('modules.filter'))
assert.ok(science.includes('prepare_features(ordered.iloc[:split],ordered.iloc[split:],feats)'),'classification and regression must fit preprocessing only on train rows')
const css=fs.readFileSync(path.join(root,'web/src/main.tsx'),'utf8')
assert.match(css,/import '\.\/syllabus\.css'/)
console.log('PASS: 19 routes retain prior 12; six real-data syllabus labs, class/regression, kmeans/ward/divisive, Apriori/FP/Eclat and method-source lineage')
