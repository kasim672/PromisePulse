const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'..')
const read=filename=>fs.readFileSync(path.join(root,filename),'utf8')
const app=read('web/src/App.tsx')
const css=read('web/src/soft-cyan.css')
const legacy=['web/src/styles.css','web/src/premium.css','web/src/measured-glass.css','web/src/theme.css']
assert.doesNotMatch(app,/WAREHOUSE CONNECTED|INITIALIZING|DATA NOT LOADED/,'status text should be removed from header')
assert.doesNotMatch(app,/header-version|header-online/,'badge markup must not return')
for(const f of legacy)assert.doesNotMatch(read(f),/\.header-(?:version|online)/,'unused badge styling must not return: '+f)
assert.match(app,/className="header-search" onClick=\{\(\) => setSearchOpen\(true\)\}/,'search palette interaction must stay intact')
assert.match(app,/Search dashboards, charts and labs/,'search should indicate what it opens')
assert.match(css,/\.header-actions\s*\{[^}]*flex:1 1 auto/s,'action row must fill remaining header space')
assert.match(css,/\.header-actions \.header-search\s*\{[^}]*flex:1 1 auto/s,'search must absorb free space')
assert.match(css,/\.header-actions \.header-search>kbd\s*\{[^}]*margin-left:auto/s,'keyboard shortcut should align to right')
assert.match(css,/@media\(max-width:760px\)/,'responsive search at tablet')
assert.match(css,/@media\(max-width:480px\)/,'compact mobile search')
assert.match(read('web/scripts/capture-current-docs.mjs'),/Header connection badge was intentionally removed/,'screenshot capture must wait on data rather than badge')
console.log('PASS header: removed warehouse badge; full-width responsive accessible search; maintained command palette')
