const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const zlib=require('node:zlib')
const root=path.resolve(__dirname,'../web/dist')
const html=fs.readFileSync(path.join(root,'index.html'),'utf8')
const tag=html.match(/<script[^>]*type="module"[^>]*src="([^"]+\.js)"/)||html.match(/<script[^>]*src="([^"]+\.js)"[^>]*type="module"/)
assert.ok(tag,'Vite entry script missing')
const name=tag[1].replace(/^\/?/,'')
const entry=fs.readFileSync(path.join(root,name))
const gzip=zlib.gzipSync(entry).length
const files=fs.readdirSync(path.join(root,'assets'))
const chunks=files.filter(x=>x.endsWith('.js')&&!x.includes('worker'))
const db=chunks.filter(x=>x.startsWith('db-'))
assert.ok(chunks.length>=5,'Workspace JS not split into route chunks')
assert.ok(db.length>0,'DuckDB engine must be in a separate on-demand chunk')
assert.ok(gzip<110000,'Initial JS entry gzip budget exceeded: '+gzip+' bytes')
assert.ok(fs.statSync(path.join(root,'data/fact_orders.parquet')).size>0,'Warehouse Parquet must ship')
console.log('PASS performance: entry JS gzip '+Math.round(gzip/1024)+' KiB; '+chunks.length+' route/vendor chunks; DuckDB deferred')
