import {chromium} from 'playwright'
const url=process.env.PP_BASE_URL||'http://127.0.0.1:4173/'
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']})
async function run(width,height,theme){
 const context=await browser.newContext({viewport:{width,height},colorScheme:theme,reducedMotion:'reduce'})
 const page=await context.newPage()
 const errors=[]
 page.on('pageerror',e=>errors.push(String(e)))
 try{
  await page.goto(url,{waitUntil:'domcontentloaded',timeout:60000})
  await page.locator('.pp-welcome').waitFor({state:'visible',timeout:100000})
  const nav=page.getByRole('navigation',{name:'Main navigation'})
  const period=page.getByRole('combobox',{name:'Shared purchase year'})
  await period.selectOption('2017')
  await nav.getByRole('button',{name:'Overview',exact:true}).click()
  await page.locator('.pp-dashboard').waitFor({state:'visible',timeout:100000})
  if(await page.getByRole('combobox',{name:'Analysis year'}).inputValue()!=='2017')throw Error('Year did not synchronize with Overview')
  await page.getByRole('button',{name:'Arrange dashboard widgets'}).click()
  await page.getByRole('button',{name:'Move Customer markets later'}).click()
  if(!await page.evaluate(()=>Boolean(localStorage.getItem('promisepulse-overview-widgets-v1'))))throw Error('Overview widget customization not saved')
  await page.getByRole('button',{name:'Done arranging'}).click()
  await nav.getByRole('button',{name:'Analytics Atlas',exact:true}).click()
  await page.locator('.atlas-page').waitFor({state:'visible',timeout:100000})
  if(await page.locator('#atlas-year').inputValue()!=='2017')throw Error('Atlas did not inherit year')
  await page.getByRole('combobox',{name:'Shared customer state'}).selectOption('SP')
  if(await page.locator('#atlas-state').inputValue()!=='SP')throw Error('Atlas did not inherit state')
  const focus=page.getByRole('button',{name:/^Focus on /}).first()
  await focus.waitFor({state:'visible',timeout:100000})
  await focus.click()
  await page.locator('.atlas-chart-expanded').waitFor({state:'visible'})
  await page.keyboard.press('Escape')
  await page.locator('.atlas-chart-expanded').waitFor({state:'hidden'})
  await nav.getByRole('button',{name:'Customer Cohorts',exact:true}).click()
  await page.locator('#research-state').waitFor({state:'visible',timeout:100000})
  if(await page.locator('#research-year').inputValue()!=='2017'||await page.locator('#research-state').inputValue()!=='SP')throw Error('Research filters not synchronized')
  await nav.getByRole('button',{name:'Data Mining Lab',exact:true}).click()
  await page.locator('.syllabus-hub-grid .syllabus-hub-card').first().waitFor({state:'visible',timeout:100000})
  await page.locator('.syllabus-hub-grid .syllabus-hub-card').first().getByRole('button',{name:'Open analysis'}).click()
  const tabs=page.getByRole('navigation',{name:'Data Mining Lab sections'})
  await tabs.getByRole('button',{name:'Clustering Lab',exact:true}).click()
  await page.getByRole('region',{name:'Algorithm walkthrough'}).waitFor({state:'visible',timeout:100000})
  await page.getByRole('button',{name:/Next step/}).click()
  await page.getByText('Step 2 of 4').waitFor({state:'visible'})
  await tabs.getByRole('button',{name:'Pattern Mining',exact:true}).click()
  await page.getByRole('button',{name:'Eclat',exact:true}).click()
  await page.getByRole('heading',{name:'Index baskets vertically'}).waitFor({state:'visible'})
  await nav.getByRole('button',{name:'Pipeline & Quality',exact:true}).click()
  const lineage=page.getByRole('region',{name:'Interactive ETL lineage'})
  await lineage.waitFor({state:'visible',timeout:100000})
  await lineage.locator('button').last().click()
  await lineage.getByText(/Stage \d+ of \d+/).waitFor({state:'visible'})
  await nav.getByRole('button',{name:'Welcome',exact:true}).click()
  await page.getByRole('button',{name:'Arrange shortcuts'}).click()
  await page.getByRole('button',{name:'Move Overview later'}).click()
  if(!await page.evaluate(()=>Boolean(localStorage.getItem('promisepulse-workspace-order-v1'))))throw Error('Customized order not saved')
  await page.getByRole('button',{name:'Restore default order'}).click()
  await page.getByRole('button',{name:'Finish arranging'}).click()
  await page.getByRole('button',{name:/Create a printable research report|^Report$/}).first().click()
  const dialog=page.getByRole('dialog',{name:'Create a report'})
  await dialog.waitFor({state:'visible',timeout:100000})
  await dialog.getByRole('heading',{name:'Warehouse record volumes'}).waitFor({state:'visible'})
  await page.evaluate(()=>{window.print=()=>{document.documentElement.dataset.printCalled='yes'}})
  await dialog.getByRole('button',{name:'Print / Save as PDF'}).click()
  await page.waitForFunction(()=>document.documentElement.dataset.printCalled==='yes')
  await dialog.getByRole('button',{name:'Close report'}).click()
  if(errors.length)throw Error('Browser JS errors: '+errors.join(' | '))
  console.log('PASS V6 '+width+'x'+height+' '+theme)
 }finally{await context.close()}
}
try{
 for(const [w,h,t] of [[1440,900,'light'],[1440,900,'dark'],[390,844,'light'],[390,844,'dark']])await run(w,h,t)
}catch(error){console.error('FAIL V6 browser:',error);process.exitCode=1}finally{await browser.close()}
